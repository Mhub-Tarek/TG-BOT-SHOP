def _load_emoji_ids() -> dict[str, str]:
    if not _IDS_PATH.exists():
        return {}
    try:
        return json.loads(_IDS_PATH.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return {}


def method_custom_emoji_id(method: str) -> str | None:
    key = _METHOD_TO_EMOJI_KEY.get(method)
    if not key:
        return None
    return _load_emoji_ids().get(key)


def method_button_text(method: str) -> str:
    """Button label without emoji prefix (custom icon renders separately)."""
    return METHOD_TEXT.get(method, method.replace("_", " ").title())


def method_label(method: str) -> str:
    """Full label with fallback emoji if custom icons not configured."""
    if method_custom_emoji_id(method):
        return method_button_text(method)
    return METHOD_FALLBACK.get(method, method_button_text(method))


def tg_emoji(emoji_id: str | None, fallback_char: str) -> str:
    """HTML tg-emoji tag for message text (requires parse_mode HTML)."""
    if not emoji_id:
        return fallback_char
    return f'<tg-emoji emoji-id="{emoji_id}">{fallback_char}</tg-emoji>'


def money(amount: float) -> str:
    """$20 for whole dollars, $20.50 when cents matter."""
    a = float(amount)
    if a == int(a):
        return f"${int(a)}"
    return f"${a:.2f}"
